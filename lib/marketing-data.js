export function catalogPageUrl(catalog, page) {
  if (!catalog) return '';
  if (catalog.pdfUrl) return `${catalog.pdfUrl}#page=${page}`;
  if (catalog.catalogUrl.includes('flipsnack')) return `${catalog.catalogUrl}&p=${page}`;
  return `${catalog.catalogUrl}#p=${page}`;
}
